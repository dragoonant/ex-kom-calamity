// node tools/flow-shots.mjs <outdir> [w h] : title -> briefing -> battle -> a few orders, screenshots along the way.
import { chromium } from 'playwright';
import { mkdirSync } from 'node:fs';
const [, , out = 'shots', w = '1440', h = '900'] = process.argv;
mkdirSync(out, { recursive: true });
const port = process.env.PW_PORT ?? '5231';
const b = await chromium.launch({ executablePath: process.env.PW_CHROMIUM ?? '/opt/pw-browsers/chromium', args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--autoplay-policy=no-user-gesture-required'] });
const p = await b.newPage({ viewport: { width: +w, height: +h } });
p.on('pageerror', (e) => console.log('pageerror', e.message));
p.on('console', (m) => { if (m.type() === 'error') console.log('console', m.text().slice(0, 200)); });
await p.goto(`http://localhost:${port}/`);
await p.waitForSelector('[data-testid=title]');
await p.waitForTimeout(1200);
await p.screenshot({ path: `${out}/1-title.png` });
await p.click('[data-testid=new]');
await p.waitForSelector('[data-testid=briefing]');
await p.waitForTimeout(800);
await p.screenshot({ path: `${out}/2-briefing.png` });
await p.click('text=Next'); await p.click('text=Next');
await p.waitForTimeout(600);
await p.screenshot({ path: `${out}/3-briefing-yard.png` });
await p.click('[data-testid=skip-brief]');
await p.click('[data-testid=deploy]');
await p.waitForSelector('[data-testid=battle]');
await p.waitForTimeout(4000);
await p.evaluate(() => window.__ib.advance(2));
await p.screenshot({ path: `${out}/4-battle.png` });
await p.evaluate(() => window.__ib.tapTile(6, 16));
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/5-selected.png` });
await p.evaluate(() => window.__ib.tapTile(6, 13));
await p.evaluate(() => window.__ib.advance(1.2));
await p.waitForTimeout(1500);
await p.screenshot({ path: `${out}/6-moved.png` });
await b.close();
console.log('done');
